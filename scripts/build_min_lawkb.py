def main() -> None:
    (LAWKB / "laws").mkdir(parents=True, exist_ok=True)
    (LAWKB / "text").mkdir(parents=True, exist_ok=True)
    (LAWKB / "VERSION").write_text(STORE_VERSION + "\n", encoding="utf-8")

    total = 0
    for lf in LAWS:
        for v in lf["article_version"]:
            text = v.pop("text")
            (LAWKB / "text" / f"{v['version_id']}.txt").write_bytes(text.encode("utf-8"))
            v["text_hash"] = "sha256:" + hashlib.sha256(text.encode("utf-8")).hexdigest()
            v["text_ref"] = f"text/{v['version_id']}.txt"
            total += 1
        out = LAWKB / "laws" / f"{lf['law']['law_id']}.yaml"
        out.write_text(
            yaml.safe_dump(lf, allow_unicode=True, sort_keys=False, width=10**6),
            encoding="utf-8",
        )
        print(f"wrote {out.name}: {len(lf['article_version'])} versions")
    print(f"total article versions: {total}")
    # R16 增补（民法典 12 条 + 5 部法律 7 条）单一事实源在 add_lawkb_laws_r16.py，
    # 幂等：已存在的条文/法律跳过，末尾整体装载校验。
    import subprocess
    import sys

    subprocess.run(
        [sys.executable, str(Path(__file__).resolve().parent / "add_lawkb_laws_r16.py")],
        check=True,
    )


if __name__ == "__main__":
    main()
