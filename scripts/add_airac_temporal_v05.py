def main() -> int:
    items = [json.loads(l) for l in PATH.read_text(encoding="utf-8").splitlines() if l.strip()]
    existing = {it["id"] for it in items}
    canaries = {it["canary"] for it in items}
    added = 0
    for it in ITEMS:
        assert it["id"] not in existing, it["id"]
        assert it["canary"] not in canaries, it["canary"]
        items.append(it)
        added += 1
    PATH.write_text(
        "".join(json.dumps(it, ensure_ascii=False) + "\n" for it in items),
        encoding="utf-8",
    )
    print(f"added {added}, total {len(items)} -> {PATH}")
    return 0


